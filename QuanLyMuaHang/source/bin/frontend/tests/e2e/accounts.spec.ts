import { test, expect } from '@playwright/test'
import { mockApi } from './fixtures'

// All credentials below are synthetic API fixtures, never local/real account passwords.
const temporaryPassword = 'synthetic-only-password'

test('creates an account with application roles and an active employee link', async ({ page }, testInfo) => {
  const state = await mockApi(page, { signedIn: true })
  state.employees.push({ ...state.employees[0], id: 11, employeeCode: 'NV-STOP', fullName: 'Nhân viên mẫu đã ngừng', status: 'INACTIVE' })
  await page.goto('/admin/users')
  await expect(page.getByRole('table')).toContainText('member@fixture.test')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('accounts.png'), fullPage: true })
  await page.getByRole('button', { name: 'Thêm tài khoản', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Thêm tài khoản', exact: true })
  await dialog.getByLabel('Email đăng nhập *', { exact: true }).fill('new-member@fixture.test')
  await dialog.getByLabel('Tên hiển thị *', { exact: true }).fill('Tài khoản mới mẫu')
  await dialog.getByLabel('Mật khẩu tạm *', { exact: true }).fill(temporaryPassword)
  await dialog.getByLabel('Nhập lại mật khẩu tạm *', { exact: true }).fill(temporaryPassword)
  const roleGroup = dialog.getByRole('group', { name: 'Ứng dụng và vai trò *', exact: true })
  await expect(roleGroup.getByText('Mua hàng', { exact: true })).toBeVisible()
  await expect(roleGroup.getByText('Nhân sự', { exact: true })).toBeVisible()
  await expect(roleGroup.getByText('Quản trị toàn hệ thống', { exact: true })).toBeVisible()
  await roleGroup.getByRole('checkbox', { name: 'Nhân viên kế hoạch', exact: true }).check()
  await roleGroup.getByRole('checkbox', { name: 'Quản lý nhân sự', exact: true }).check()
  await dialog.getByLabel('Liên kết nhân viên', { exact: true }).fill('Nhân viên mẫu')
  await expect(dialog.getByRole('button', { name: 'NV001 · Nhân viên mẫu An', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'NV-STOP · Nhân viên mẫu đã ngừng', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'NV001 · Nhân viên mẫu An', exact: true }).click()
  await expect(dialog.getByText('NV001 · Nhân viên mẫu An', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('account-dialog.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Tạo tài khoản', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('Người dùng cần đổi mật khẩu tạm khi đăng nhập lần đầu.')
  await expect(page.getByRole('row').filter({ hasText: 'new-member@fixture.test' })).toContainText('Cần đổi mật khẩu')
  expect(state.writes[0]).toMatchObject({ method: 'POST', path: '/api/admin/users', body: { email: 'new-member@fixture.test', displayName: 'Tài khoản mới mẫu', employeeId: 10 } })
  expect(state.writes[0].body.roleCodes).toEqual(expect.arrayContaining(['PLANNER', 'HR_MANAGER']))
  expect(state.writes[0].body).not.toHaveProperty('modules')
  await expect(page.getByText(temporaryPassword, { exact: true })).toHaveCount(0)
  expect(state.unexpectedRequests).toEqual([])
})

test('edits roles and account status only after confirming the final changes', async ({ page }) => {
  const state = await mockApi(page, { signedIn: true })
  await page.goto('/admin/users')
  await page.getByRole('button', { name: 'Sửa tài khoản member@fixture.test', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Sửa tài khoản', exact: true })
  await expect(dialog.getByLabel('Email đăng nhập *', { exact: true })).toHaveAttribute('readonly', '')
  await dialog.getByRole('checkbox', { name: 'Chỉ xem', exact: true }).uncheck()
  await dialog.getByRole('checkbox', { name: 'Quản lý nhân sự', exact: true }).check()
  await dialog.getByLabel('Trạng thái', { exact: true }).selectOption('LOCKED')
  await dialog.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Các phiên đăng nhập của tài khoản sẽ bị thu hồi.')
  expect(state.writes).toHaveLength(0)
  await dialog.getByLabel('Tên hiển thị *', { exact: true }).fill('Tài khoản mẫu cập nhật')
  await expect(dialog.getByRole('button', { name: 'Xác nhận lưu', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click()
  expect(state.writes).toHaveLength(0)
  await dialog.getByRole('button', { name: 'Xác nhận lưu', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('row').filter({ hasText: 'member@fixture.test' })).toContainText('Khóa')
  await expect(page.getByRole('row').filter({ hasText: 'member@fixture.test' })).toContainText('Quản lý nhân sự')
  expect(state.writes[0]).toMatchObject({ method: 'PUT', path: '/api/admin/users/20', body: { displayName: 'Tài khoản mẫu cập nhật', employeeId: null, status: 'LOCKED', roleCodes: ['HR_MANAGER'] } })
  expect(state.writes[0].body).not.toHaveProperty('email')
  expect(state.writes[0].body).not.toHaveProperty('initialPassword')
})

test('resets a temporary password after confirmation and accepts an empty 200 response', async ({ page }) => {
  const state = await mockApi(page, { signedIn: true })
  await page.goto('/admin/users')
  await page.getByRole('button', { name: 'Đặt lại mật khẩu member@fixture.test', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Đặt lại mật khẩu', exact: true })
  await expect(dialog).toContainText('thu hồi các phiên hiện có và yêu cầu đổi mật khẩu')
  await dialog.getByLabel('Mật khẩu tạm mới *', { exact: true }).fill(temporaryPassword)
  await dialog.getByLabel('Nhập lại mật khẩu tạm *', { exact: true }).fill(temporaryPassword)
  await dialog.getByRole('button', { name: 'Đặt lại mật khẩu', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Xác nhận đặt lại' })).toBeVisible()
  expect(state.writes).toHaveLength(0)
  const replacement = 'synthetic-only-replacement'
  await dialog.getByLabel('Mật khẩu tạm mới *', { exact: true }).fill(replacement)
  await dialog.getByLabel('Nhập lại mật khẩu tạm *', { exact: true }).fill(replacement)
  await expect(dialog.getByRole('button', { name: 'Xác nhận đặt lại' })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Đặt lại mật khẩu', exact: true }).click()
  expect(state.writes).toHaveLength(0)
  await dialog.getByRole('button', { name: 'Xác nhận đặt lại' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('Đã đặt lại mật khẩu tạm và thu hồi các phiên đăng nhập.')
  await expect(page.getByRole('table')).toContainText('Cần đổi mật khẩu')
  expect(state.writes[0]).toMatchObject({ method: 'POST', path: '/api/admin/users/20/reset-password', body: { temporaryPassword: replacement } })
  await expect(page.getByText(replacement, { exact: true })).toHaveCount(0)
})

test('keeps account edits after a role lookup failure and a last-admin conflict', async ({ page }) => {
  const state = await mockApi(page, { signedIn: true })
  state.accounts[0].roleCodes = ['ADMIN']
  state.roleStatus = 503
  let attemptedUpdates = 0
  await page.route('**/api/admin/users/20', async (route) => {
    if (route.request().method() !== 'PUT') return route.fallback()
    if (++attemptedUpdates === 1) return route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ code: 'LAST_ADMIN', message: 'Không thể vô hiệu hóa quản trị viên cuối cùng.' }) })
    return route.fallback()
  })
  await page.goto('/admin/users')
  await page.getByRole('button', { name: 'Sửa tài khoản member@fixture.test', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Sửa tài khoản', exact: true })
  await dialog.getByLabel('Tên hiển thị *', { exact: true }).fill('Tên mẫu được giữ lại')
  await expect(dialog.getByRole('alert')).toContainText('Chưa tải được vai trò.')
  await expect(dialog.getByRole('button', { name: 'Lưu thay đổi', exact: true })).toBeDisabled()
  state.roleStatus = 200
  await dialog.getByRole('button', { name: 'Tải lại vai trò' }).click()
  await expect(dialog.getByRole('button', { name: 'Lưu thay đổi', exact: true })).toBeEnabled()
  await dialog.getByRole('checkbox', { name: 'Quản trị viên', exact: true }).uncheck()
  await dialog.getByRole('checkbox', { name: 'Chỉ xem', exact: true }).check()
  await dialog.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click()
  await dialog.getByRole('button', { name: 'Xác nhận lưu', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('Không thể vô hiệu hóa quản trị viên cuối cùng.')
  await expect(dialog.getByLabel('Tên hiển thị *', { exact: true })).toHaveValue('Tên mẫu được giữ lại')
  await expect(dialog.getByRole('checkbox', { name: 'Chỉ xem', exact: true })).toBeChecked()
  await expect(page.getByText('Đã cập nhật tài khoản và thu hồi các phiên đăng nhập hiện có.', { exact: true })).toHaveCount(0)
  await dialog.getByRole('checkbox', { name: 'Quản trị viên', exact: true }).check()
  await dialog.getByRole('checkbox', { name: 'Chỉ xem', exact: true }).uncheck()
  await dialog.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click()
  await dialog.getByRole('button', { name: 'Xác nhận lưu', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('table')).toContainText('Tên mẫu được giữ lại')
  expect(attemptedUpdates).toBe(2)
  expect(state.unexpectedRequests).toEqual([])
})

test('retries and paginates account reads without exposing write actions to a custom reader', async ({ page }) => {
  const state = await mockApi(page, { role: 'ACCOUNT_READER', permissions: ['USER_READ'], signedIn: true })
  const sample = state.accounts[0]
  state.accounts = Array.from({ length: 26 }, (_, index) => ({ ...sample, id: index + 20, email: `member${index + 1}@fixture.test`, displayName: `Tài khoản mẫu ${index + 1}` }))
  state.userStatus = 503
  await page.goto('/admin/users')
  await expect(page.getByRole('table')).toHaveCount(0)
  state.userStatus = 200
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click()
  await expect(page.getByRole('table')).toContainText('member1@fixture.test')
  await expect(page.getByRole('button', { name: 'Thêm tài khoản' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Sửa tài khoản / })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Đặt lại mật khẩu / })).toHaveCount(0)
  await page.getByRole('button', { name: 'Sau', exact: true }).click()
  await expect(page.getByText('Trang 2 / 2', { exact: true })).toBeVisible()
  await expect(page.getByRole('table')).toContainText('member26@fixture.test')
  await expect(page.getByRole('button', { name: 'Sau', exact: true })).toBeDisabled()
  await page.goto('/admin/employees')
  await expect(page.getByRole('heading', { name: 'Bạn không có quyền truy cập' })).toBeVisible()
  expect(state.writes).toHaveLength(0)
  expect(state.unexpectedRequests).toEqual([])
})
