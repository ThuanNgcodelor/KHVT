import { test, expect } from '@playwright/test'
import { mockApi } from './fixtures'

test('creates and edits an employee using department and position lookups', async ({ page }, testInfo) => {
  const state = await mockApi(page, { signedIn: true })
  await page.goto('/modules')
  await expect(page.getByRole('heading', { name: 'Ứng dụng của bạn' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('portal.png'), fullPage: true })
  await page.getByRole('link', { name: /^Nhân sự/ }).click()
  await expect(page.getByRole('table')).toContainText('Nhân viên mẫu An')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('employees.png'), fullPage: true })

  await page.getByRole('button', { name: 'Thêm nhân viên', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Thêm nhân viên', exact: true })
  await expect(dialog.getByLabel('Mã nhân viên *', { exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  expect(await dialog.evaluate((element) => element.contains(document.activeElement))).toBe(true)
  await dialog.getByLabel('Mã nhân viên *', { exact: true }).fill('NV002')
  await dialog.getByLabel('Họ và tên *', { exact: true }).fill('Nhân viên mẫu Bình')
  await dialog.getByLabel('Phòng ban', { exact: true }).selectOption('1')
  await dialog.getByLabel('Chức vụ', { exact: true }).selectOption('1')
  await dialog.getByLabel('Ngày vào làm', { exact: true }).fill('2026-10-10')
  await page.screenshot({ path: testInfo.outputPath('employee-dialog.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('Đã lưu hồ sơ Nhân viên mẫu Bình.')
  await expect(page.getByRole('table')).toContainText('NV002')
  expect(state.writes[0]).toMatchObject({ method: 'POST', path: '/api/personnel/employees', body: {
    employeeCode: 'NV002', fullName: 'Nhân viên mẫu Bình', departmentId: 1, positionId: 1,
    email: null, phone: null, joinedAt: '2026-10-10',
  } })

  const edit = page.getByRole('button', { name: 'Sửa Nhân viên mẫu Bình', exact: true })
  await edit.click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(edit).toBeFocused()
  await edit.click()
  const editing = page.getByRole('dialog', { name: 'Sửa hồ sơ nhân viên' })
  await editing.getByLabel('Họ và tên *', { exact: true }).fill('Nhân viên mẫu Bình cập nhật')
  await editing.getByLabel('Số điện thoại', { exact: true }).fill('0000000000')
  await editing.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click()
  await expect(editing).toHaveCount(0)
  await expect(page.getByRole('table')).toContainText('Nhân viên mẫu Bình cập nhật')
  expect(state.writes[1]).toMatchObject({ method: 'PUT', path: '/api/personnel/employees/11', body: { phone: '0000000000' } })
  expect(state.unexpectedRequests).toEqual([])
})

test('retains employee input through lookup failure and duplicate-code conflict', async ({ page }) => {
  const state = await mockApi(page, { role: 'HR_MANAGER', signedIn: true })
  state.lookupStatus = 503
  state.employeeFailures = 1
  await page.goto('/admin/employees')
  await page.getByRole('button', { name: 'Thêm nhân viên' }).click()
  const dialog = page.getByRole('dialog', { name: 'Thêm nhân viên', exact: true })
  await dialog.getByLabel('Mã nhân viên *', { exact: true }).fill('NV001')
  await dialog.getByLabel('Họ và tên *', { exact: true }).fill('Hồ sơ mẫu chưa lưu')
  await expect(dialog.getByRole('alert')).toContainText('Chưa tải được phòng ban hoặc chức vụ.')
  await expect(dialog.getByRole('button', { name: 'Lưu hồ sơ' })).toBeDisabled()
  expect(state.writes).toHaveLength(0)
  state.lookupStatus = 200
  await dialog.getByRole('button', { name: 'Tải lại danh mục' }).click()
  await expect(dialog.getByRole('button', { name: 'Lưu hồ sơ' })).toBeEnabled()
  await dialog.getByRole('button', { name: 'Lưu hồ sơ' }).click()
  await expect(dialog.getByRole('alert')).toHaveText('Mã nhân viên đã tồn tại')
  await expect(dialog.getByLabel('Họ và tên *', { exact: true })).toHaveValue('Hồ sơ mẫu chưa lưu')
  await expect(page.getByText('Đã lưu hồ sơ Hồ sơ mẫu chưa lưu.', { exact: true })).toHaveCount(0)
  await dialog.getByLabel('Mã nhân viên *', { exact: true }).fill('NV003')
  await dialog.getByRole('button', { name: 'Lưu hồ sơ' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('table')).toContainText('NV003')
  expect(state.writes).toHaveLength(2)
  expect(state.unexpectedRequests).toEqual([])
})

test('requires confirmation for stopping and reactivating an employee', async ({ page }) => {
  const state = await mockApi(page, { role: 'HR_MANAGER', signedIn: true })
  await page.goto('/admin/employees')
  const stop = page.getByRole('button', { name: 'Ngừng Nhân viên mẫu An', exact: true })
  await stop.click()
  const stopping = page.getByRole('dialog', { name: 'Ngừng nhân viên' })
  await expect(stopping).toContainText('Tài khoản liên kết sẽ bị vô hiệu hóa và các phiên đăng nhập bị thu hồi.')
  await expect(stopping.getByRole('button', { name: 'Quay lại' })).toBeFocused()
  expect(state.writes).toHaveLength(0)
  await page.keyboard.press('Escape')
  await expect(stop).toBeFocused()
  expect(state.writes).toHaveLength(0)
  await stop.click()
  await stopping.getByRole('button', { name: 'Xác nhận ngừng' }).click()
  await expect(stopping).toHaveCount(0)
  await expect(page.getByRole('table')).toContainText('Đã ngừng')
  expect(state.writes[0].path).toBe('/api/personnel/employees/10/deactivate')

  await page.getByRole('button', { name: 'Kích hoạt Nhân viên mẫu An', exact: true }).click()
  const activating = page.getByRole('dialog', { name: 'Kích hoạt nhân viên' })
  await expect(activating).toContainText('không tự mở lại tài khoản đăng nhập.')
  expect(state.writes).toHaveLength(1)
  await activating.getByRole('button', { name: 'Xác nhận kích hoạt' }).click()
  await expect(activating).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('Tài khoản đăng nhập cần được quản trị viên kiểm tra riêng.')
  expect(state.writes[1].path).toBe('/api/personnel/employees/10/activate')
})

test('paginates and filters personnel while a read-only custom role cannot mutate', async ({ page }) => {
  const state = await mockApi(page, { role: 'PERSONNEL_READER', permissions: ['PERSONNEL_READ'], signedIn: true })
  const sample = state.employees[0]
  state.employees = Array.from({ length: 26 }, (_, index) => ({ ...sample, id: index + 10,
    employeeCode: `NV${String(index + 1).padStart(3, '0')}`, fullName: `Nhân viên mẫu ${index + 1}`,
    status: index === 25 ? 'INACTIVE' : 'ACTIVE',
  }))
  await page.goto('/admin/employees')
  await expect(page.getByRole('table')).toContainText('NV001')
  await expect(page.getByRole('button', { name: 'Thêm nhân viên' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Sửa / })).toHaveCount(0)
  await page.getByRole('button', { name: 'Sau', exact: true }).click()
  await expect(page.getByText('Trang 2 / 2', { exact: true })).toBeVisible()
  await expect(page.getByRole('table')).toContainText('NV026')
  await page.getByLabel('Mã hoặc tên nhân viên').fill('NV026')
  await page.getByRole('button', { name: 'Tìm kiếm', exact: true }).click()
  await expect(page.getByText('Trang 1 / 1', { exact: true })).toBeVisible()
  await page.getByLabel('Trạng thái', { exact: true }).selectOption('ACTIVE')
  await expect(page.getByText('Không có nhân viên phù hợp', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Xóa lọc' }).click()
  await page.getByLabel('Trạng thái', { exact: true }).selectOption('INACTIVE')
  await expect(page.getByRole('table')).toContainText('NV026')
  await expect(page.getByRole('button', { name: /^Kích hoạt / })).toHaveCount(0)
  await page.goto('/admin/departments')
  await expect(page.getByRole('table')).toContainText('Phòng KHVT')
  await expect(page.getByRole('button', { name: 'Thêm phòng ban' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Sửa / })).toHaveCount(0)
  expect(state.writes).toHaveLength(0)
})

test('creates a department and confirms deactivation again after form changes', async ({ page }) => {
  const state = await mockApi(page, { role: 'HR_MANAGER', signedIn: true })
  await page.goto('/admin/departments')
  await page.getByRole('button', { name: 'Thêm phòng ban' }).click()
  const creating = page.getByRole('dialog', { name: 'Thêm phòng ban', exact: true })
  await creating.getByLabel('Mã phòng ban', { exact: true }).fill('PB-MAU')
  await creating.getByLabel('Tên phòng ban *', { exact: true }).fill('Phòng ban mẫu')
  await creating.getByLabel('Phòng ban cấp trên').selectOption('1')
  await creating.getByRole('button', { name: 'Lưu', exact: true }).click()
  await expect(creating).toHaveCount(0)
  await expect(page.getByRole('table')).toContainText('Phòng ban mẫu')
  expect(state.writes[0]).toMatchObject({ method: 'POST', path: '/api/personnel/departments', body: { parentId: 1, active: true } })

  await page.getByRole('button', { name: 'Sửa Phòng ban mẫu', exact: true }).click()
  const editing = page.getByRole('dialog', { name: 'Sửa phòng ban', exact: true })
  await expect(editing.getByLabel('Phòng ban cấp trên').locator('option[value="2"]')).toHaveCount(0)
  await editing.getByRole('checkbox', { name: 'Đang hoạt động' }).uncheck()
  await editing.getByRole('button', { name: 'Lưu', exact: true }).click()
  await expect(editing.getByRole('alert')).toContainText('Bạn đang ngừng phòng ban này.')
  expect(state.writes).toHaveLength(1)
  await editing.getByLabel('Tên phòng ban *', { exact: true }).fill('Phòng ban mẫu cập nhật')
  await expect(editing.getByRole('button', { name: 'Xác nhận lưu', exact: true })).toHaveCount(0)
  await editing.getByRole('button', { name: 'Lưu', exact: true }).click()
  expect(state.writes).toHaveLength(1)
  await editing.getByRole('button', { name: 'Xác nhận lưu', exact: true }).click()
  await expect(editing).toHaveCount(0)
  await expect(page.getByRole('row').filter({ hasText: 'Phòng ban mẫu cập nhật' })).toContainText('Đã ngừng')
  expect(state.writes[1]).toMatchObject({ method: 'PUT', path: '/api/personnel/departments/2', body: { active: false } })
})

